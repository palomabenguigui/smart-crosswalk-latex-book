#!/usr/bin/env python3
"""make_plan_figures.py – T3 (WBS tree) and T5 (Gantt, months 1-12) as TikZ, generated from data/wbs.csv.
Output: figures/tikz/t3-wbs.tex, figures/tikz/t5-gantt.tex. Hebrew nodes use the 'rtl' style (DS-01); colours from smartcross.cls.
Flow is right-to-left (root on the right); month axis stays LTR (numeric axis, QA-04)."""
import csv
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
MILESTONE_TASKS = {'1.3': 'M1', '3.4': 'M2', '5.3': 'M3'}   # permit, acceptance protocol, final report (end of task)


def load():
    rows = list(csv.DictReader((ROOT / 'data/wbs.csv').open(encoding='utf-8')))
    wps = {}
    for r in rows:
        wps.setdefault(r['wp_id'], {'name': r['wp_name_he'], 'tasks': []})['tasks'].append(r)
    return wps


def num(t):
    return '\\num{%s}' % t


def wbs(wps):
    out = ['% T3 – WBS tree (generated by scripts/make_plan_figures.py from data/wbs.csv; do not edit by hand)',
           '\\begin{tikzpicture}[x=1mm,y=1mm,',
           '  lab/.style={rtl,font=\\sffamily\\fontsize{7.5}{9}\\selectfont,text=Asphalt,align=flush right,inner sep=1.5pt},',
           '  tsk/.style={lab,draw=Asphalt!60,line width=.4pt,fill=Paper,text width=72mm,anchor=east},',
           '  wp/.style={lab,draw=AsphaltDeep,fill=Concrete,line width=.6pt,text width=27mm,align=center,anchor=east,font=\\sffamily\\bfseries\\fontsize{7.5}{9}\\selectfont},',
           '  edge/.style={AsphaltLight,line width=.6pt}]']
    rowh, gap = 6.2, 3.0
    y, wp_y = 0.0, {}
    placed = []
    for wid, w in wps.items():
        ys = []
        for t in w['tasks']:
            ys.append(y); placed.append((t, y)); y -= rowh
        wp_y[wid] = (ys[0] + ys[-1]) / 2
        y -= gap
    top, bottom = 0.0, y + gap
    root_y = (top + bottom) / 2
    xr_root, xr_wp, xr_task = 138, 100, 70   # right edges (anchor=east)
    out.append('  \\node[lab,draw=AsphaltDeep,fill=Asphalt,text=StripeWhite,text width=20mm,align=center,anchor=east,'
               'font=\\sffamily\\bfseries\\fontsize{8}{10}\\selectfont] (root) at (%g,%.1f) {מעבר חצייה חכם: פיילוט %s חודשים};'
               % (xr_root, root_y, num(12)))
    for wid, w in wps.items():
        out.append('  \\node[wp] (%s) at (%g,%.1f) {%s~%s};' % (wid, xr_wp, wp_y[wid], num(wid[2:]), w['name']))
        out.append('  \\draw[edge] (root.west) -- ++(-4,0) |- (%s.east);' % wid)
    for t, yy in placed:
        tid = t['task_id']
        n = 'T' + tid.replace('.', 'x')
        out.append('  \\node[tsk] (%s) at (%g,%.1f) {%s~%s};' % (n, xr_task, yy, num(tid), t['task_name_he']))
        out.append('  \\draw[edge] (WP%s.west) -- ++(-1.5,0) |- (%s.east);' % (tid.split('.')[0], n))
    out.append('\\end{tikzpicture}')
    # node names: WP ids are 'WP1'.. -> TikZ-safe already
    return '\n'.join(out) + '\n'


def gantt(wps):
    mw, rh, lw = 6.0, 5.0, 56.0       # month width, row height, label column width (mm)
    x0 = 0.0
    xr = x0 + 12 * mw + 2 + lw       # right edge of label column
    out = ['% T5 – Gantt chart, months 1-12 (generated by scripts/make_plan_figures.py from data/wbs.csv; do not edit by hand)',
           '\\begin{tikzpicture}[x=1mm,y=1mm,',
           '  lab/.style={rtl,font=\\sffamily\\fontsize{7.5}{9}\\selectfont,text=Asphalt,align=flush right,inner sep=1pt,anchor=east},',
           '  grid/.style={Hairline,line width=.3pt}]']
    rows = []
    for wid, w in wps.items():
        rows.append(('wp', wid, w, min(int(t['start_month']) for t in w['tasks']), max(int(t['end_month']) for t in w['tasks'])))
        for t in w['tasks']:
            rows.append(('task', wid, t, int(t['start_month']), int(t['end_month'])))
    n = len(rows)
    # month header + grid
    for m in range(1, 13):
        cx = x0 + (m - 0.5) * mw
        out.append('  \\node[font=\\sffamily\\fontsize{7.5}{9}\\selectfont,text=Asphalt,inner sep=0,anchor=base] at (%.1f,2.4) {%d};' % (cx, m))
    out.append('  \\node[lab,anchor=east,font=\\sffamily\\bfseries\\fontsize{7.5}{9}\\selectfont] at (%.1f,3.5) {חודש};' % (xr))
    for m in range(0, 13):
        out.append('  \\draw[grid] (%.1f,0) -- (%.1f,%.1f);' % (x0 + m * mw, x0 + m * mw, -n * rh))
    for i, (kind, wid, d, s, e) in enumerate(rows):
        yc = -(i + 0.5) * rh
        if kind == 'wp':
            out.append('  \\fill[Concrete] (%.1f,%.1f) rectangle (%.1f,%.1f);' % (x0, yc - rh / 2, xr, yc + rh / 2))
            out.append('  \\node[lab,anchor=east,font=\\sffamily\\bfseries\\fontsize{7.5}{9}\\selectfont] at (%.1f,%.1f) {%s~%s};'
                       % (xr - 1, yc, num(wid[2:]), d['name']))
            out.append('  \\fill[Asphalt] (%.1f,%.1f) rectangle (%.1f,%.1f);'
                       % (x0 + (s - 1) * mw, yc - 0.9, x0 + e * mw, yc + 0.9))
        else:
            out.append('  \\node[lab] at (%.1f,%.1f) {%s~%s};' % (xr - 1, yc, num(d['task_id']), d['task_name_he']))
            out.append('  \\fill[SignalAmber,draw=SignalAmberDark,line width=.5pt] (%.1f,%.1f) rectangle (%.1f,%.1f);'
                       % (x0 + (s - 1) * mw + .3, yc - 1.5, x0 + e * mw - .3, yc + 1.5))
            ms = MILESTONE_TASKS.get(d['task_id'])
            if ms:
                mx = x0 + e * mw
                out.append('  \\node[diamond,draw=AsphaltDeep,fill=SignalRed,line width=.5pt,inner sep=1.4pt] at (%.1f,%.1f) {};' % (mx, yc))
                out.append('  \\node[font=\\sffamily\\bfseries\\fontsize{6.5}{7}\\selectfont,text=SignalRed,anchor=west,inner sep=1pt] at (%.1f,%.1f) {%s};'
                           % (mx + 2, yc, ms))
    out.append('  \\draw[Asphalt,line width=.5pt] (%.1f,0) -- (%.1f,0) (%.1f,%.1f) -- (%.1f,%.1f);'
               % (x0, xr, x0, -n * rh, xr, -n * rh))
    # legend (right to left: swatch, then its label to the left of it)
    ly = -n * rh - 5
    right = xr - 3
    out.append('  \\node[diamond,draw=AsphaltDeep,fill=SignalRed,line width=.5pt,inner sep=1.4pt] at (%.1f,%.1f) {};' % (right, ly))
    out.append('  \\node[lab] at (%.1f,%.1f) {אבן דרך: M1 היתר, M2 קבלה, M3 דוח סיום};' % (right - 3, ly))
    out.append('  \\fill[SignalAmber,draw=SignalAmberDark,line width=.5pt] (%.1f,%.1f) rectangle ++(8,3);' % (right - 62, ly - 1.5))
    out.append('  \\node[lab] at (%.1f,%.1f) {משימה};' % (right - 64, ly))
    out.append('  \\fill[Asphalt] (%.1f,%.1f) rectangle ++(8,1.8);' % (right - 90, ly - .9))
    out.append('  \\node[lab] at (%.1f,%.1f) {חבילת עבודה};' % (right - 92, ly))
    out.append('\\end{tikzpicture}')
    return '\n'.join(out) + '\n'


def make():
    wps = load()
    d = ROOT / 'figures/tikz'
    d.mkdir(parents=True, exist_ok=True)
    s = wbs(wps)
    for wid in wps:   # TikZ node names WP1.. : name them in the node line
        s = s.replace('(%s) at' % wid, '(WP%s) at' % wid[2:]).replace('(%s.east)' % wid, '(WP%s.east)' % wid[2:])
    (d / 't3-wbs.tex').write_text(s, encoding='utf-8')
    (d / 't5-gantt.tex').write_text(gantt(wps), encoding='utf-8')
    return 'figures/tikz/t3-wbs.tex, figures/tikz/t5-gantt.tex'


if __name__ == '__main__':
    print(make())
